// Access modifiers - control visibility and accessibility
// ------------------------------------------------------------------------------------
// public     - anywhere within the program
// private    - anywhere within the same class
// protected  - anywhere the same package and its subclasses outside the package
// default    - anywhere within the same package
//
//

// Encapsulation - prevents direct access to object's internal state (data hiding)
// ------------------------------------------------------------------------------------
// declare class variable/attributes as private
// provide getters and setters to access and update the value of private

// Benefits;
// security and data integrity  -
// flexibility and maintenance  -
// read/write control           - read and write control with setters and getters
//
//

