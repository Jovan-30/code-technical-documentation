// The Core Components Required to Run Your Website
// --------------------------------------------------------------------------------------
// Compute - severs/computers that do processing required to run website
// Database - store info about product, customers, etc.
// Storage - storing things like marketing documents/pictures of products selling
// Network - to connect to website through internet
// Secure - data about customers, payment info can't be hacked or stolen

// Problem
// Purchase all the hardware and software and hire systems engineer, security, etc.
// Thus, paying a lot for setup and maintenance. New customers result in problems due
// to not enough infastructure to handle it all.

// Past Solution:
// Better job estimating demand such as how much traffic website wil have, more infastructure,
// needing servers all across the world

// Solution:
// To move to the cloud.


// Moving to the Cloud
// --------------------------------------------------------------------------------------
// Data Centers - contain servers, network cables, routers, etc.

// Pros:
// Move to the cloud instead, esentially renting the cloud and someone else manages for you
// Pay for what you need and when you need, don't pay for all infastructure, employees




