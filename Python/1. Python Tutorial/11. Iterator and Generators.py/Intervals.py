# In Python, intervals refer to ranges of values. An interval is often 
# used to specify a range of values that a variable or expression can take.
# Intervals can be used to define the range of acceptable values for a given 
# problem, to limit the range of values used in a calculation, or to specify a 
# range of values to be processed or analyzed.

nums = [1, 2, 4]

for num in nums:
    print(num)